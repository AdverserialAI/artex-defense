// Generate the explicit built-in prompt upgrade from the current English defaults.
package main

import (
	"fmt"
	"os"
	"sort"
	"strings"
	"unicode"

	"artex/agent"
	"artex/db"
)

func literal(text string) string {
	var b strings.Builder
	b.WriteString("U&'")
	for _, r := range text {
		switch {
		case r == '\'':
			b.WriteString("''")
		case r == '\\':
			b.WriteString("\\\\")
		case unicode.Is(unicode.Han, r):
			fmt.Fprintf(&b, "\\%04X", r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('\'')
	return b.String()
}
func body(text string) string {
	const tag = "$ARTEX_PROMPT$"
	if strings.Contains(text, tag) {
		panic("prompt contains SQL delimiter")
	}
	return tag + text + tag
}
func keys(values map[string]string) []string {
	result := make([]string, 0, len(values))
	for key := range values {
		result = append(result, key)
	}
	sort.Strings(result)
	return result
}
func main() {
	out := os.Stdout
	fmt.Fprintln(out, "-- Generated by go run ./scripts/generate-prompt-upgrade; do not edit by hand.")
	fmt.Fprintln(out, "-- Explicit upgrade: replaces known scenario template bodies; appends prompt versions only when changed.")
	fmt.Fprintln(out, "BEGIN;")
	prompts := agent.BuiltinPromptSeeds()
	planners := agent.PlannerDomainSeeds()
	planners[db.ExternalPentestTemplateName] = prompts["planner"]
	workers := map[string]string{db.ExternalPentestTemplateName: prompts["worker"]}
	for _, seed := range agent.WorkerDomainSeeds() {
		workers[seed.NKey] = seed.Body
	}
	for _, group := range []struct {
		table  string
		values map[string]string
	}{{"planner_templates", planners}, {"worker_templates", workers}} {
		for _, key := range keys(group.values) {
			fmt.Fprintf(out, "\nUPDATE %s SET body=%s,updated_at=now() WHERE nkey=%s;\n", group.table, body(group.values[key]), literal(key))
		}
	}
	prompts["trace_cleaner"] = agent.TraceCleanerDefaultPrompt
	prompts["retester"] = agent.RetesterDefaultPrompt
	for _, key := range keys(prompts) {
		value := body(prompts[key])
		fmt.Fprintf(out, `%sWITH current_default AS (
 SELECT a.id AS agent_id,p.template_text
 FROM agents a LEFT JOIN agent_prompts p ON p.id=a.current_prompt_id
 WHERE a.key=%s
), inserted AS (
 INSERT INTO agent_prompts(agent_id,version,template_text,note,updated_by)
 SELECT agent_id,COALESCE((SELECT max(version) FROM agent_prompts WHERE agent_id=current_default.agent_id),0)+1,
 %s,'English defaults upgrade','system'
 FROM current_default WHERE COALESCE(template_text,'') IS DISTINCT FROM %s
 RETURNING agent_id,id
)
UPDATE agents SET current_prompt_id=inserted.id FROM inserted WHERE agents.id=inserted.agent_id;
`, "\n", literal(key), value, value)
	}
	fmt.Fprintln(out, "\nCOMMIT;")
}
